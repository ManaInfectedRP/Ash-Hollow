export const itemSpriteUrl = (id: string) =>
  (ATLAS_ITEMS as readonly string[]).includes(id) ? `assets/atlas/items/${id}.png` : null;

/** Player body sheet for the equipped armor. */
export function playerBodyKey(armorId: string | null) {
  const a = armorId && (PLAYER_ARMOR_LOOKS as readonly string[]).includes(armorId) ? armorId : 'naked';
  return `player-${a}`;
}

/** Weapon sheet for the equipped weapon, or null when unarmed. */
export function weaponSheetKey(weaponId: string) {
  return (PLAYER_WEAPON_LOOKS as readonly string[]).includes(weaponId) ? `weapon-${weaponId}` : null;
}

/** Weapon bone for one player frame: grip position (frame-local px) and angle in degrees. */
export interface Bone {
  x: number;
  y: number;
  a: number;
  show: boolean;
  /** off-hand (shield) bone */
  sx: number;
  sy: number;
  /** shield raised in front of the body */
  front: boolean;
  /** off-hand angle in degrees (second dagger) */
  sa?: number;
}
export const WEAPON_STEP = 5;

export function preloadSprites(load: Phaser.Loader.LoaderPlugin) {
  for (const a of PLAYER_ARMOR_LOOKS) load.atlas(`player-${a}`, `assets/sprites/player-${a}.png`, `assets/sprites/player-${a}.json`);
  for (const w of PLAYER_WEAPON_LOOKS) load.atlas(`weapon-${w}`, `assets/sprites/weapon-${w}.png`, `assets/sprites/weapon-${w}.json`);
  load.json('player-bones', 'assets/sprites/player.bones.json');
  for (const s of SHIELD_LOOKS) load.atlas(`shield-${s}`, `assets/sprites/shield-${s}.png`, `assets/sprites/shield-${s}.json`);
  for (const k of ENEMY_SHEETS) load.atlas(k, `assets/sprites/${k}.png`, `assets/sprites/${k}.json`);
  for (const id of ATLAS_ITEMS) load.image(`item:${id}`, `assets/atlas/items/${id}.png`);
  for (const id of ATLAS_PROPS) load.image(`prop:${id}`, `assets/atlas/props/${id}.png`);
}
